"""Tests for the demo asset pipeline: markers, barcodes, wires, manifests.

Run: python3 -m unittest tvcast.tests.test_demo -v
These tests are headless: they use only generated bytes and the recorded
assets in demos/, without sockets or ffmpeg.
"""
import json
import tempfile
import unittest
from pathlib import Path

from ..demo import audio, frames, wire


ROOT = Path(__file__).resolve().parent.parent.parent
ASSETS = ROOT / "demos" / "assets"


class FrameIdentity(unittest.TestCase):
    def test_barcode_roundtrip(self):
        for program in (1, 2, 3):
            for index in (0, 1, 47, 249):
                frame = frames.render_frame(program, index)
                self.assertEqual(frames.read_barcode(frame), (program, index))

    def test_barcode_rejects_corruption(self):
        frame = bytearray(frames.render_frame(1, 24))
        # damage one full barcode bit cell (both bars): the CRC must reject it
        x0 = frames.BAR_X + 2 * 8 * (frames.BAR_W + frames.BAR_GAP)
        for yy in range(frames.BAR_Y, frames.BAR_Y + frames.BAR_H):
            for xx in range(x0, x0 + 2 * (frames.BAR_W + frames.BAR_GAP) - 2):
                frame[yy * frames.WIDTH + xx] ^= 0xFF
        self.assertIsNone(frames.read_barcode(bytes(frame)))

    def test_neighbouring_frames_differ(self):
        a = frames.render_frame(1, 10)
        b = frames.render_frame(1, 11)
        self.assertNotEqual(frames.read_barcode(a), frames.read_barcode(b))
        self.assertNotEqual(a, b)


class AudioMarkers(unittest.TestCase):
    def test_marker_positions_and_types(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "m.wav"
            audio.write_wav(path, 6.5)
            rate, pcm = audio.read_pcm16(path)
        markers = audio.detect_markers(pcm, rate)
        seconds = [m["second"] for m in markers]
        self.assertEqual(seconds, [0, 1, 2, 3, 4, 5, 6])
        kinds = {m["second"]: m["kind"] for m in markers}
        self.assertEqual(kinds[0], "mark")
        self.assertEqual(kinds[5], "mark")
        self.assertEqual(kinds[1], "tick")


class WireFormat(unittest.TestCase):
    def test_write_read_roundtrip_and_order(self):
        entries = [(300, 1, b"second"), (100, 0, b"first")]
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "x.wire"
            wire.write_wire(path, entries)
            read = list(wire.read_wire(path))
        self.assertEqual([e[1] for e in read], [0, 1])
        self.assertEqual([e[2] for e in read], [b"first", b"second"])

    def test_rejects_foreign_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "bad.wire"
            path.write_bytes(b"nope")
            with self.assertRaises(ValueError):
                list(wire.read_wire(path))


class FaultPlan(unittest.TestCase):
    def setUp(self):
        self.packets = [{
            "index": i, "seq16": i, "ext_seq": i, "rtp_ts": i * 1000,
            "payload": b"", "offset_us": i * 10_000, "frame": i,
        } for i in range(100)]

    def test_drop_creates_one_window(self):
        emissions, events, summary = wire.apply_faults(
            self.packets,
            [{"action": "drop", "at_ms": 200, "count": 10}],
            reorder_timeout=0.25)
        self.assertEqual(summary["dropped_packets"], 10)
        self.assertEqual(events[0]["packet_index"], 20)
        self.assertEqual(len(emissions), 90)

    def test_duplicate_adds_copies(self):
        emissions, events, summary = wire.apply_faults(
            self.packets,
            [{"action": "duplicate", "at_ms": 100, "count": 5,
              "delay_ms": 90}],
            reorder_timeout=0.25)
        self.assertEqual(summary["duplicate_copies"], 5)
        self.assertEqual(len(emissions), 105)
        self.assertEqual(events[0]["action"], "duplicate")

    def test_reorder_within_timeout_is_accepted(self):
        emissions, events, summary = wire.apply_faults(
            self.packets,
            [{"action": "reorder", "at_ms": 100, "count": 12,
              "hold_count": 12, "delay_ms": 150}],
            reorder_timeout=0.25)
        self.assertEqual(summary["delayed_packets"], 12)

    def test_reorder_beyond_timeout_is_rejected(self):
        with self.assertRaises(ValueError):
            wire.apply_faults(
                self.packets,
                [{"action": "reorder", "at_ms": 100, "count": 12,
                  "hold_count": 12, "delay_ms": 400}],
                reorder_timeout=0.25)

    def test_unknown_action_rejected(self):
        with self.assertRaises(ValueError):
            wire.apply_faults(self.packets, [{"action": "mangle",
                                              "at_ms": 1, "count": 1}],
                              reorder_timeout=0.25)


class RecordedAssets(unittest.TestCase):
    """The checked-in assets must exist and match their manifests."""

    def test_every_manifest_matches_files(self):
        manifests = sorted(ASSETS.glob("*.json"))
        self.assertTrue(manifests, "no demo assets checked in")
        for path in manifests:
            manifest = json.loads(path.read_text(encoding="utf-8"))
            wire_path = ASSETS / manifest["wire"]["file"]
            self.assertTrue(wire_path.exists(), wire_path)
            self.assertEqual(wire.sha256_file(wire_path),
                             manifest["wire"]["sha256"])
            content = ROOT / manifest["content"]["file"]
            self.assertTrue(content.exists(), content)
            self.assertEqual(wire.sha256_file(content),
                             manifest["content"]["sha256"])
            content_manifest = json.loads(
                (ROOT / manifest["content"]["content_manifest"])
                .read_text(encoding="utf-8"))
            self.assertEqual(
                content_manifest["program"]["number"],
                manifest["program"]["number"])

    def test_wire_has_expected_packet_identity(self):
        manifest = json.loads(
            (ASSETS / "loss-burst.json").read_text(encoding="utf-8"))
        records = list(wire.read_wire(ASSETS / manifest["wire"]["file"]))
        self.assertEqual(len(records), manifest["wire"]["packet_records"])
        seqs = [wire.rtp.parse_rtp(payload)["seq"] for _, _, payload in records]
        self.assertEqual(seqs[0], manifest["wire"]["start_seq"])
        # per-record order is emission order; a drop leaves a seq16 gap
        dropped = manifest["summary"]["dropped_packets"]
        self.assertEqual(dropped, 35)
        self.assertEqual(manifest["fault_events"][0]["count"], dropped)
        expected_span = manifest["summary"]["original_packets"]
        self.assertEqual(len(seqs), expected_span - dropped)
        # sequence numbers must cover the declared identity range
        first_ext = manifest["wire"]["start_seq"]
        last_ext = first_ext + expected_span - 1
        gap_start = manifest["fault_events"][0]["ext_seq"]
        gap_end = gap_start + dropped - 1
        present = set(seqs)
        self.assertNotIn(gap_start & 0xFFFF, present)
        self.assertNotIn(gap_end & 0xFFFF, present)
        self.assertIn((gap_end + 1) & 0xFFFF, present)
        self.assertEqual(last_ext & 0xFFFF, manifest["wire"]["end_seq"])

    def test_manifest_events_are_inside_wire_window(self):
        for path in sorted(ASSETS.glob("*.json")):
            manifest = json.loads(path.read_text(encoding="utf-8"))
            window = manifest["wire"]["duration_ms"] + 1
            for event in manifest["fault_events"]:
                self.assertLessEqual(event["at_ms"], window, path.name)
                self.assertGreaterEqual(event["at_ms"], 0, path.name)


if __name__ == "__main__":
    unittest.main()
